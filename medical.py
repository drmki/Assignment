# Manage visits, medical records, prescriptions, and laboratory tests.

from datetime import datetime  # Import date and time support.


class MedicalRecord:
    # Initialize a visit medical record.
    def __init__(self, record_id, summary=""):
        self.__record_id = record_id  # Store medical record ID.
        self.__summary = summary  # Store record summary.
        self.__attachments = []  # Store attachment references.
        self.__created_at = datetime.now()  # Store record creation time.

    # Return record ID.
    def get_record_id(self):
        return self.__record_id

    # Return record summary.
    def get_summary(self):
        return self.__summary

    # Update record summary.
    def set_summary(self, summary):
        self.__summary = summary

    # Return a copy of attachment references.
    def get_attachments(self):
        return list(self.__attachments)

    # Replace attachment references.
    def set_attachments(self, attachments):
        self.__attachments = list(attachments)

    # Add a document reference.
    def add_attachment(self, file_name):
        self.__attachments.append(file_name)

    # Generate a readable visit summary.
    def generate_summary(self):
        return self.__summary


