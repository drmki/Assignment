class Prescription:
    # Initialize a prescription.
    def __init__(self, prescription_id):
        self.__prescription_id = prescription_id  # Store prescription ID.
        self.__issue_date = datetime.now()  # Store issue date.
        self.__status = "DRAFT"  # Set initial status.
        self.__medicines = []  # Initialize medicine collection.

    # Return prescription status.
    def get_status(self):
        return self.__status

    # Update prescription status.
    def set_status(self, status):
        self.__status = status

    # Return a copy of prescribed medicines.
    def get_medicines(self):
        return list(self.__medicines)

    # Add a medicine to the prescription.
    def add_medicine(self, medicine):
        self.__medicines.append(medicine)

    # Mark the prescription as sent to the pharmacy.
    def send_to_pharmacy(self):
        if not self.__medicines:
            raise ValueError("Add at least one medicine before sending.")
        self.__status = "SENT_TO_PHARMACY"


