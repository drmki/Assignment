class LabOrder:
    # Initialize a laboratory order.
    def __init__(self, order_id, test_name, charge):
        self.__order_id = order_id  # Store order ID.
        self.__test_name = test_name  # Store test name.
        self.__order_date = datetime.now()  # Store order date.
        self.__status = "ORDERED"  # Set initial order status.
        self.__charge = charge  # Store laboratory charge.
        self.__result = None  # No result is available initially.

    # Return test name.
    def get_test_name(self):
        return self.__test_name

    # Update test name.
    def set_test_name(self, name):
        self.__test_name = name

    # Return order status.
    def get_status(self):
        return self.__status

    # Update order status.
    def set_status(self, status):
        allowed = {"ORDERED", "IN_PROGRESS", "COMPLETED", "CANCELLED"}
        if status not in allowed:
            raise ValueError("Invalid laboratory order status.")
        self.__status = status

    # Return laboratory charge.
    def get_charge(self):
        return self.__charge

    # Update laboratory charge.
    def set_charge(self, charge):
        if charge < 0:
            raise ValueError("Charge cannot be negative.")
        self.__charge = charge

    # Return the attached result.
    def get_result(self):
        return self.__result

    # Update order lifecycle status.
    def update_status(self, status):
        self.set_status(status)

    # Attach a result and mark the order completed.
    def add_result(self, result):
        self.__result = result
        self.__status = "COMPLETED"


class MedicalVisit:
    # Initialize a medical visit.
    def __init__(self, visit_id, visit_date, diagnosis, notes):
        self.__visit_id = visit_id  # Store visit ID.
        self.__visit_date = visit_date  # Store visit date.
        self.__diagnosis = diagnosis  # Store diagnosis.
        self.__notes = notes  # Store consultation notes.
        self.__vitals = {}  # Initialize vital measurements.
        self.__record = MedicalRecord(visit_id, notes)  # Create visit record.
        self.__prescriptions = []  # Initialize prescriptions.
        self.__lab_orders = []  # Initialize laboratory orders.

    # Return visit ID.
    def get_visit_id(self):
        return self.__visit_id

    # Return diagnosis.
    def get_diagnosis(self):
        return self.__diagnosis

    # Update diagnosis.
    def set_diagnosis(self, diagnosis):
        self.__diagnosis = diagnosis

    # Return consultation notes.
    def get_notes(self):
        return self.__notes

    # Update consultation notes.
    def set_notes(self, notes):
        self.__notes = notes
        self.__record.set_summary(notes)

    # Return a copy of vitals.
    def get_vitals(self):
        return dict(self.__vitals)

    # Replace the vitals dictionary.
    def set_vitals(self, vitals):
        self.__vitals = dict(vitals)

    # Add or update one vital measurement.
    def add_vital(self, name, value):
        self.__vitals[name] = value

    # Return the medical record.
    def get_record(self):
        return self.__record

    # Return a copy of prescriptions.
    def get_prescriptions(self):
        return list(self.__prescriptions)

    # Add a prescription.
    def add_prescription(self, prescription):
        self.__prescriptions.append(prescription)

    # Return a copy of laboratory orders.
    def get_lab_orders(self):
        return list(self.__lab_orders)

    # Add a laboratory order.
    def add_lab_order(self, lab_order):
        self.__lab_orders.append(lab_order)