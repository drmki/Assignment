class Patient:
    # Initialize the patient profile.
    def __init__(self, patient_id, name, date_of_birth, phone, email,
                 address, emergency_contact, insurance_details,
                 known_allergies, medical_history_summary):
        self.__patient_id = patient_id  # Store unique patient ID.
        self.__name = name  # Store patient name.
        self.__date_of_birth = date_of_birth  # Store date of birth.
        self.__phone = phone  # Store patient phone.
        self.__email = email  # Store patient email.
        self.__address = address  # Store residential address.
        self.__emergency_contact = emergency_contact  # Store emergency contact.
        self.__insurance_details = insurance_details  # Store insurance details.
        self.__known_allergies = list(known_allergies)  # Copy allergy list.
        self.__medical_history_summary = medical_history_summary  # Store history.
        self.__appointments = []  # Initialize patient's appointments.

    # Return patient name.
    def get_name(self):
        return self.__name

    # Update patient name.
    def set_name(self, name):
        self.__name = name

    # Return patient phone.
    def get_phone(self):
        return self.__phone

    # Update patient phone.
    def set_phone(self, phone):
        self.__phone = phone

    # Return patient email.
    def get_email(self):
        return self.__email

    # Update patient email.
    def set_email(self, email):
        self.__email = email

    # Return patient address.
    def get_address(self):
        return self.__address

    # Update patient address.
    def set_address(self, address):
        self.__address = address

    # Return a copy of known allergies.
    def get_known_allergies(self):
        return list(self.__known_allergies)

    # Update known allergies.
    def set_known_allergies(self, allergies):
        self.__known_allergies = list(allergies)

    # Return insurance details.
    def get_insurance_details(self):
        return self.__insurance_details

    # Update insurance details.
    def set_insurance_details(self, details):
        self.__insurance_details = details

    # Add an appointment to the patient.
    def add_appointment(self, appointment):
        self.__appointments.append(appointment)

    # Return the patient's appointments.
    def view_appointments(self):
        return list(self.__appointments)

    # Return a visit summary for the requested visit.
    def download_visit_summary(self, visit_id):
        for appointment in self.__appointments:  # Examine patient appointments.
            visit = appointment.get_visit()  # Retrieve the associated visit.
            if visit is not None and visit.get_visit_id() == visit_id:
                return visit.get_record().generate_summary()  # Return summary.
        return "No visit summary found."