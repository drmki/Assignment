# Store staff, doctor, receptionist, and patient classes.

class Staff:
    # Initialize common staff details.
    def __init__(self, staff_id, name, contact_number, email, role, working_hours):
        self._staff_id = staff_id  # Store protected staff ID.
        self._name = name  # Store protected staff name.
        self._contact_number = contact_number  # Store protected phone.
        self._email = email  # Store protected email.
        self._role = role  # Store protected role.
        self._working_hours = working_hours  # Store protected schedule.

    # Return staff name.
    def get_name(self):
        return self._name

    # Update staff name.
    def set_name(self, name):
        self._name = name

    # Return contact number.
    def get_contact_number(self):
        return self._contact_number

    # Update contact number.
    def set_contact_number(self, number):
        self._contact_number = number

    # Return email address.
    def get_email(self):
        return self._email

    # Update email address.
    def set_email(self, email):
        self._email = email

    # Return staff role.
    def get_role(self):
        return self._role

    # Update staff role.
    def set_role(self, role):
        self._role = role

    # Return working hours.
    def get_working_hours(self):
        return self._working_hours

    # Update working hours.
    def set_working_hours(self, hours):
        self._working_hours = hours


class Doctor(Staff):
    # Initialize doctor details and inherited staff details.
    def __init__(self, staff_id, name, contact_number, email,
                 working_hours, speciality, qualifications, consultation_fee):
        super().__init__(
            staff_id, name, contact_number, email, "Doctor", working_hours
        )  # Initialize the parent Staff class.
        self.__speciality = speciality  # Store medical speciality.
        self.__qualifications = qualifications  # Store qualifications.
        self.__consultation_fee = consultation_fee  # Store consultation fee.

    # Return speciality.
    def get_speciality(self):
        return self.__speciality

    # Update speciality.
    def set_speciality(self, speciality):
        self.__speciality = speciality

    # Return qualifications.
    def get_qualifications(self):
        return self.__qualifications

    # Update qualifications.
    def set_qualifications(self, qualifications):
        self.__qualifications = qualifications

    # Return consultation fee.
    def get_consultation_fee(self):
        return self.__consultation_fee

    # Update consultation fee after validating the value.
    def set_consultation_fee(self, fee):
        if fee < 0:
            raise ValueError("Consultation fee cannot be negative.")
        self.__consultation_fee = fee


