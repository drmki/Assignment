# Manage invoices, insurance claims, and payments.

from datetime import datetime  # Import payment date support.


class Invoice:
    # Initialize an invoice for a medical visit.
    def __init__(self, invoice_id, consultation_fee, lab_charges,
                 medication_charges, other_charges=0.0):
        self.__invoice_id = invoice_id  # Store invoice ID.
        self.__consultation_fee = consultation_fee  # Store consultation fee.
        self.__lab_charges = lab_charges  # Store laboratory charges.
        self.__medication_charges = medication_charges  # Store medicine charges.
        self.__other_charges = other_charges  # Store other service charges.
        self.__insurance_coverage = 0.0  # Initialize insurer contribution.
        self.__co_pay = 0.0  # Initialize patient responsibility.
        self.__total_amount = 0.0  # Initialize gross amount.
        self.__status = "UNPAID"  # Set initial invoice status.
        self.calculate_total()  # Calculate the initial invoice.

    # Return invoice ID.
    def get_invoice_id(self):
        return self.__invoice_id

    # Return total patient payable amount.
    def get_total_amount(self):
        return self.__co_pay

    # Update total patient payable amount.
    def set_total_amount(self, amount):
        if amount < 0:
            raise ValueError("Invoice amount cannot be negative.")
        self.__co_pay = amount

    # Return invoice status.
    def get_status(self):
        return self.__status

    # Update invoice status.
    def set_status(self, status):
        self.__status = status

    # Calculate gross charges and current patient responsibility.
    def calculate_total(self):
        charges = (
            self.__consultation_fee
            + self.__lab_charges
            + self.__medication_charges
            + self.__other_charges
        )  # Add all charge categories.
        self.__total_amount = round(charges, 2)  # Store gross amount.
        self.__co_pay = round(
            self.__total_amount - self.__insurance_coverage, 2
        )  # Calculate amount payable by patient.
        return self.__total_amount  # Return gross amount.

    # Apply insurance coverage without exceeding gross charges.
    def apply_insurance(self, coverage):
        if coverage < 0:
            raise ValueError("Coverage cannot be negative.")
        if coverage > self.__total_amount:
            raise ValueError("Coverage cannot exceed total charges.")
        self.__insurance_coverage = round(coverage, 2)  # Store coverage.
        self.__co_pay = round(
            self.__total_amount - self.__insurance_coverage, 2
        )  # Recalculate patient responsibility.

    # Generate a readable invoice summary.
    def generate_invoice(self):
        return (
            f"Invoice #{self.__invoice_id} | "
            f"Gross: {self.__total_amount:.2f} | "
            f"Insurance: {self.__insurance_coverage:.2f} | "
            f"Patient payable: {self.__co_pay:.2f} | "
            f"Status: {self.__status}"
        )  # Return invoice details.


class Payment:
    # Initialize a payment record.
    def __init__(self, payment_id, amount, method):
        self.__payment_id = payment_id  # Store payment ID.
        self.__amount = amount  # Store payment amount.
        self.__method = method  # Store payment method.
        self.__status = "PENDING"  # Set initial payment status.
        self.__payment_date = None  # No completed payment date yet.

    # Return payment amount.
    def get_amount(self):
        return self.__amount

    # Update payment amount.
    def set_amount(self, amount):
        if amount <= 0:
            raise ValueError("Payment amount must be positive.")
        self.__amount = amount

    # Return payment method.
    def get_method(self):
        return self.__method

    # Update payment method.
    def set_method(self, method):
        self.__method = method

    # Return payment status.
    def get_status(self):
        return self.__status

    # Update payment status.
    def set_status(self, status):
        self.__status = status

    # Process a simulated payment.
    def process_payment(self):
        allowed_methods = {"CARD", "MOBILE_WALLET", "INSURANCE"}
        if self.__method not in allowed_methods:
            raise ValueError("Unsupported payment method.")
        self.__status = "COMPLETED"  # Simulate successful processing.
        self.__payment_date = datetime.now()  # Store completion time.
        return True  # Indicate simulated success.


class InsuranceClaim:
    # Initialize an insurance claim.
    def __init__(self, claim_id, provider_name, claimed_amount):
        self.__claim_id = claim_id  # Store claim ID.
        self.__provider_name = provider_name  # Store insurer name.
        self.__claimed_amount = claimed_amount  # Store requested amount.
        self.__approved_amount = 0.0  # Initialize approved amount.
        self.__status = "DRAFT"  # Set initial claim status.

    # Return claim status.
    def get_status(self):
        return self.__status

    # Update claim status.
    def set_status(self, status):
        self.__status = status

    # Submit the claim to the insurer.
    def submit_claim(self):
        self.__status = "SUBMITTED"

    # Record the approved amount.
    def approve_claim(self, amount):
        if amount < 0 or amount > self.__claimed_amount:
            raise ValueError("Approved amount is invalid.")
        self.__approved_amount = amount
        self.__status = "APPROVED"

    # Mark the claim as rejected.
    def reject_claim(self):
        self.__status = "REJECTED"