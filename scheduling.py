# Manage appointment booking, rescheduling, and cancellation.

from datetime import datetime  # Import date and time support.


class Appointment:
    # Initialize an appointment.
    def __init__(self, appointment_id, patient, doctor,
                 appointment_datetime, duration_minutes, reason):
        self.__appointment_id = appointment_id  # Store appointment ID.
        self.__patient = patient  # Link the appointment to its patient.
        self.__doctor = doctor  # Link the appointment to its doctor.
        self.__appointment_datetime = appointment_datetime  # Store appointment time.
        self.__duration_minutes = duration_minutes  # Store duration.
        self.__reason = reason  # Store appointment reason.
        self.__status = "BOOKED"  # Set initial appointment status.
        self.__visit = None  # No visit exists before the consultation.

    # Return appointment ID.
    def get_appointment_id(self):
        return self.__appointment_id

    # Return patient.
    def get_patient(self):
        return self.__patient

    # Return doctor.
    def get_doctor(self):
        return self.__doctor

    # Return appointment date and time.
    def get_appointment_datetime(self):
        return self.__appointment_datetime

    # Update appointment date and time.
    def set_appointment_datetime(self, date_time):
        if not isinstance(date_time, datetime):
            raise TypeError("Appointment time must be a datetime object.")
        self.__appointment_datetime = date_time

    # Return appointment duration.
    def get_duration_minutes(self):
        return self.__duration_minutes

    # Update appointment duration.
    def set_duration_minutes(self, minutes):
        if minutes <= 0:
            raise ValueError("Duration must be greater than zero.")
        self.__duration_minutes = minutes

    # Return appointment status.
    def get_status(self):
        return self.__status

    # Update appointment status.
    def set_status(self, status):
        self.__status = status

    # Return the associated visit.
    def get_visit(self):
        return self.__visit

    # Link a medical visit to this appointment.
    def set_visit(self, visit):
        self.__visit = visit

    # Confirm a booked appointment.
    def confirm(self):
        if self.__status != "BOOKED":
            raise ValueError("Only booked appointments can be confirmed.")
        self.__status = "CONFIRMED"

    # Reschedule an active appointment.
    def reschedule(self, date_time):
        if self.__status not in ("BOOKED", "CONFIRMED"):
            raise ValueError("Only active appointments can be rescheduled.")
        self.set_appointment_datetime(date_time)

    # Cancel an active appointment.
    def cancel(self):
        if self.__status not in ("BOOKED", "CONFIRMED"):
            raise ValueError("Appointment cannot be cancelled in its current state.")
        self.__status = "CANCELLED"